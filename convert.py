"""Convert HSLVision (HF parquet) -> YOLO detection layout.

bbox convention verified empirically as COCO absolute top-left xywh
(w*h matches the dataset `area` field on all sampled boxes).
"""
import io, sys, glob, re
from pathlib import Path
from collections import Counter
import pyarrow.parquet as pq
from PIL import Image

ROOT = Path(__file__).parent
RAW = ROOT / "raw" / "data"
OUT = ROOT / "dataset"

# dataset category ids are 1..7 (0 = background) -> YOLO 0..6
NAMES = ["Ball", "Goalpost", "K1", "L-Intersections",
         "Penalty Marks", "T-Intersections", "X-Intersections"]

SPLITS = ["train", "valid", "test"]


def safe_stem(filename):
    """Strip the images/ prefix + extension, and make the stem filesystem-safe."""
    stem = Path(filename).stem
    return re.sub(r"[^A-Za-z0-9._-]+", "_", stem)


def convert(split):
    files = sorted(glob.glob(str(RAW / f"{split}-*.parquet")))
    if not files:
        sys.exit(f"no parquet files for split {split}")
    img_dir = OUT / "images" / split
    lbl_dir = OUT / "labels" / split
    img_dir.mkdir(parents=True, exist_ok=True)
    lbl_dir.mkdir(parents=True, exist_ok=True)

    n_img = n_box = n_clip = n_drop = n_bg = n_empty = 0
    size_mismatch = 0
    seen = Counter()
    cls_hist = Counter()

    for f in files:
        pf = pq.ParquetFile(f)
        for batch in pf.iter_batches(batch_size=16):
            for row in batch.to_pylist():
                stem = safe_stem(row["filename"])
                seen[stem] += 1
                if seen[stem] > 1:                    # never silently overwrite
                    stem = f"{stem}__dup{seen[stem]}"

                im = Image.open(io.BytesIO(row["image"]["bytes"]))
                if im.mode != "RGB":
                    im = im.convert("RGB")
                W, H = im.size                        # trust decoded size
                if (W, H) != (row["width"], row["height"]):
                    size_mismatch += 1
                im.save(img_dir / f"{stem}.jpg", quality=95)

                lines = []
                objs = row["objects"]
                for bbox, cat in zip(objs["bbox"], objs["category"]):
                    if cat == 0:
                        n_bg += 1
                        continue
                    x, y, w, h = bbox                 # COCO absolute xywh
                    x0, y0 = x, y
                    x1, y1 = x + w, y + h
                    cx0, cy0 = max(0.0, x0), max(0.0, y0)
                    cx1, cy1 = min(float(W), x1), min(float(H), y1)
                    if (cx0, cy0, cx1, cy1) != (x0, y0, x1, y1):
                        n_clip += 1
                    if cx1 - cx0 <= 1e-3 or cy1 - cy0 <= 1e-3:
                        n_drop += 1
                        continue
                    lines.append(
                        f"{cat - 1} {(cx0+cx1)/2/W:.6f} {(cy0+cy1)/2/H:.6f} "
                        f"{(cx1-cx0)/W:.6f} {(cy1-cy0)/H:.6f}")
                    cls_hist[cat - 1] += 1

                (lbl_dir / f"{stem}.txt").write_text(
                    "\n".join(lines) + ("\n" if lines else ""))
                n_img += 1
                n_box += len(lines)
                if not lines:
                    n_empty += 1
        print(f"  [{split}] done {Path(f).name} ({n_img} imgs)", flush=True)

    dups = sum(v - 1 for v in seen.values() if v > 1)
    print(f"{split}: {n_img} images, {n_box} boxes | clipped={n_clip} "
          f"dropped={n_drop} background={n_bg} empty_imgs={n_empty} "
          f"dup_stems={dups} size_meta_mismatch={size_mismatch}", flush=True)
    return n_img, n_box, cls_hist


if __name__ == "__main__":
    totals, grand = {}, Counter()
    for split in SPLITS:
        n_img, n_box, hist = convert(split)
        totals[split] = (n_img, n_box)
        grand.update(hist)

    (ROOT / "hslvision.yaml").write_text(
        "# Generated by convert.py -- do not hand-edit.\n"
        "# `path` is absolute because ultralytics resolves relative dataset\n"
        "# paths against its settings `datasets_dir`, not this file's location.\n"
        "# Re-run `python convert.py` on a new machine to rewrite it correctly.\n"
        f"path: {OUT}\n"
        "train: images/train\n"
        "val: images/valid\n"
        "test: images/test\n\n"
        "names:\n" + "".join(f"  {i}: {n}\n" for i, n in enumerate(NAMES)))

    print("\n=== SUMMARY ===")
    ti = sum(v[0] for v in totals.values()); tb = sum(v[1] for v in totals.values())
    for k, (i, b) in totals.items():
        print(f"  {k:6s} {i:5d} images  {b:6d} boxes")
    print(f"  TOTAL  {ti:5d} images  {tb:6d} boxes   (card: 6068 imgs / 65285 boxes)")
    print("\n=== CLASS DISTRIBUTION ===")
    for i, n in enumerate(NAMES):
        print(f"  {i} {n:16s} {grand[i]:6d}")
